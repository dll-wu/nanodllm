"""Main exhibit rows and plot coordinates, retaining manuscript rounding."""

from statistics import mean

from .formatting import bpb, bpb_delta, bpb_interval, one

SEEDS = (48, 49)
HEADER = "% Generated by main_exhibits.py from the portable manuscript snapshots.\n"


def interval_mark(symbol, row, value, limits):
    lo, hi = limits
    assert lo <= value <= hi
    return rf"\{symbol}{{{row}}}{{{value:.8f}}}{{{lo:.8f}}}{{{hi:.8f}}}"


def transfer_marks(scaling, block):
    """Coordinates stay in BPB. The TeX template owns axes, symbols and row spacing."""
    panels = {"Full": [], "Development": [], "Holdout": [], "Seeds": []}
    for row, depth in enumerate((4, 8, 10, 12, 16, 20)):
        scratch = one(scaling["points"], depth=depth, family="scratch")
        child = one(scaling["points"], depth=depth, family="conversion")
        delta = child["bpb"] - scratch["bpb"]
        size = round(scratch["total_parameters"] / 1e6)
        panels["Full"].append(rf"\rowname{{{row}}}{{{size}M}}\fullmark{{{row}}}{{{delta:.8f}}}")

    metrics = (("common", "common/block_end", "nexttoken"), ("native", "native/mean_eval_seeds", "reconstruct"))
    for row, (depth, label) in enumerate(((4, "20M"), (8, "59M"), (12, "135M"), (20, "477M"))):
        row *= 1.6
        for panel in ("Development", "Holdout"):
            panels[panel].append(rf"\rowname{{{row}}}{{{label}}}")
        for metric, report_key, symbol in metrics:
            if depth == 8:
                development, holdout = [], []
                for index, seed in enumerate((50, 51, 52)):
                    dev = one(block["d8"]["paired"], conversion_lr=0.00175, seed=seed, metric=metric)
                    held = block["holdout"]["runs"][f"d8-s{seed}"]["comparisons"]["lr00175"][report_key]
                    development.append(dev["delta"])
                    holdout.append(held["delta_bpb"])
                    for seed_row, value, limits in (
                        (index, dev["delta"], dev["ci95"]),
                        (index + 3.5, held["delta_bpb"], held["confidence_interval_bpb"]),
                    ):
                        if metric == "common":
                            panels["Seeds"].append(rf"\rowname{{{seed_row}}}{{{seed}}}")
                        panels["Seeds"].append(interval_mark(symbol, seed_row, value, limits))
                for panel, values in (("Development", development), ("Holdout", holdout)):
                    panels[panel].append(rf"\{symbol}mean{{{row}}}{{{mean(values):.8f}}}")
                continue
            if depth == 4:
                record = block["d4_paired_intervals"][report_key]
                delta, interval = record["delta_bpb"], record["confidence_interval_bpb"]
            else:
                record = one(block["large"]["paired"], panel="fresh", depth=depth, metric=metric)
                delta, interval = record["delta"], record["ci95"]
            panels["Development"].append(interval_mark(symbol, row, delta, interval))
            measure = block["holdout"]["runs"][f"d{depth}"]["comparisons"]["conversion"][report_key]
            panels["Holdout"].append(
                interval_mark(symbol, row, measure["delta_bpb"], measure["confidence_interval_bpb"])
            )
    return "\n".join("\\def\\plot" + panel + "{%\n" + "\n".join(marks) + "%\n}" for panel, marks in panels.items())


def evaluation_marks(replication):
    marks = []
    for model, style in (("bd3_fixed", "fixednoise"), ("bd3_optimized", "calibratednoise")):
        values = [
            mean(one(replication["noise_canvas"], model=model, canvas=canvas, seed=s)["content_bpb"] for s in SEEDS)
            for canvas in ("legacy", "block_end")
        ]
        marks.append(rf"\{style}{{{bpb(values[0])}}}{{{bpb(values[1])}}}")
    definitions = [r"\def\drawnoise{%"] + marks + ["}"]
    for label, policy in (("reuse", "coupled"), ("fresh", "independent")):
        rows = [one(replication["decoder_replay"], group=f"mixed_bl:{policy}-k4-p1", seed=s) for s in SEEDS]
        repeat = [100 * r["repeat4"] for r in rows]
        ppl = [r["ppl_micro"] for r in rows]
        precision = 2 if max(repeat) < 1 else 1
        values = {
            "sampleppl": f"{replication['example_ppl'][label]:.1f}",
            "repeatrange": rf"{min(repeat):.{precision}f}--{max(repeat):.{precision}f}\%",
            "pplrange": f"{min(ppl):.1f}--{max(ppl):.1f}",
        }
        definitions.extend(rf"\def\{label}{key}{{{value}}}" for key, value in values.items())
    return "\n".join(definitions)


def component_rows(data):
    compute = one(data["compute"]["prediction_contrasts"], panel="fresh", a="fastv2", b="fixed")
    contrasts = data["contrasts"]
    records = (
        ("BD3 calibrated noise", "Fixed noise range", "20 TPP", contrasts["bd3_optimized"], "Canvas-sensitive gain"),
        ("Fast-v2 construction", "Fixed, token-causal", "40 TPP", contrasts["fastv2"], "Lower loss at equal tokens"),
        (
            "Fast-v2 construction",
            "Fixed, block-causal",
            "40 TPP",
            contrasts["full_budget"],
            "Gain with revised control",
        ),
        ("Fast-v2 construction", "Fixed, block-causal", "Matched FLOPs", compute, "Interval spans zero"),
        ("LLaDA 1 masking", "Scratch MDLM", "20 TPP", contrasts["llada1"], "Interval spans zero"),
        (
            "LLaDA 2.0 curriculum",
            "Fixed blocks + tail",
            "40 TPP",
            contrasts["new_curriculum"],
            "Higher loss in both seeds",
        ),
    )
    rows = []
    for candidate, control, budget, contrast, reading in records:
        estimate = bpb_delta(contrast["mean_delta"])
        interval = bpb_interval(*contrast["paired_document_bootstrap_95"])
        rows.append(" & ".join((candidate, control, budget, f"${estimate}$", f"${interval}$", reading)) + r" \\")
    return "\\def\\exhibitrows{%\n" + "\n".join(rows) + "%\n}"


def final_model_rows(block):
    tasks = block["tasks"]["depths"]["d20"]["aggregates"]["mean_nelbo__block_full_mask"]
    rows = []
    for recipe, key, label in (("scratch40", "scratch", "Scratch"), ("AR10+MDLM30", "conversion", "AR-initialized")):
        for k, policy in ((1, "Left-to-right (1)"), (4, "Confidence redraw (4)")):
            gen = one(block["large"]["generation"], depth=20, recipe=recipe, panel="fresh", decoder=f"k{k}_bl32")
            accuracy = 100 * tasks[key]["mean_raw_accuracy"]
            rows.append(
                " & ".join(
                    [
                        label if k == 1 else "",
                        f"{accuracy:.2f}" if k == 1 else "",
                        policy,
                        f"{gen['tpf']:.2f}",
                        f"{gen['tokens_sec']:.1f}",
                        f"{gen['gemma_ppl']:.1f}",
                        bpb(gen["gemma_bpb"]),
                        f"{100 * gen['repeat4']:.2f}",
                        f"{gen['eos_count']}/{gen['count']}",
                    ]
                )
                + r" \\"
            )
        if key == "scratch":
            rows.append(r"\addlinespace[2pt]")
    return "\\def\\exhibitrows{%\n" + "\n".join(rows) + "%\n}"


def model_size_rows(scaling):
    rows = []
    for point in scaling["points"]:
        if point["family"] == "scratch":
            rows.append(
                f"{point['depth']} & {point['width']} & {point['total_parameters'] / 1e6:.2f} & "
                f"{point['budget_parameters'] / 1e6:.2f}" + r" \\"
            )
    return "\\def\\exhibitrows{%\n" + "\n".join(rows) + "%\n}"


def block_rate_rows(block):
    cells = {}
    for r in block["d8_discovery_grid"]:
        if r["profile"] != "parent":
            cells["Conversion", int(r["eb"]), float(r["lr"])] = (float(r["fresh_bpb"]), float(r["fresh_native_nelbo"]))
    for r in block["d8"]["metrics"]:
        if r["recipe"] == "scratch40" and r["seed"] == 50:
            cells["Scratch", 262144, r["lr"]] = (r["fresh_common"], r["fresh_native"])
    assert len(cells) == 14
    rows = []
    for arm, batch in sorted({(arm, batch) for arm, batch, _ in cells}):
        row = [arm, f"{batch:,}"]
        for lr in (0.00175, 0.0035, 0.007, 0.014):
            pair = cells.get((arm, batch, lr))
            row.append(" / ".join(bpb(v) for v in pair) if pair else "---")
        rows.append(" & ".join(row) + r" \\")
    return "\\def\\exhibitrows{%\n" + "\n".join(rows) + "%\n}"


def decoding_control_rows(block):
    rows = []
    for depth, size in ((12, "135M"), (20, "477M")):
        for k, length in ((1, 32), (4, 16), (4, 32), (4, 64)):
            metrics = []
            for recipe in ("scratch40", "AR10+MDLM30"):
                record = one(
                    block["large"]["generation"], depth=depth, recipe=recipe, panel="fresh", decoder=f"k{k}_bl{length}"
                )
                assert record["count"] == 64
                metrics.append(
                    [
                        f"{record['gemma_ppl']:.1f}",
                        f"{record['gemma_bpb']:.3f}",
                        f"{100 * record['repeat4']:.2f}",
                        str(record["eos_count"]),
                        f"{record['tpf']:.2f}",
                    ]
                )
            cells = [size, str(k), str(length)]
            for scratch, converted in zip(*metrics, strict=True):
                cells.extend((scratch, converted))
            rows.append(" & ".join(cells) + r" \\")
        if depth == 12:
            rows.append(r"\midrule")
    return "\\def\\exhibitrows{%\n" + "\n".join(rows) + "%\n}"


def hp_grid_marks(development, tables):
    """Use the allocation snapshot and the checked scratch-table cells distributed with the paper."""
    marks = []

    def curve(name, style, points):
        coords = " ".join(f"({x},{loss:.7f})" for x, loss in points)
        marks.append(rf"\def\{name}{{\draw[{style}] plot coordinates {{{coords}}};}}")

    allocations = sorted(development["allocation_grid"], key=lambda row: row["ar_tpp"])
    curve("allocationcurve", "allocation", [(r["ar_tpp"], r["bpb"]) for r in allocations])
    for ar_tpp, name, style in [(10, "quartercurve", "quarter"), (20, "halfcurve", "half")]:
        rows = sorted((r for r in development["conversion_lr"] if r["ar_tpp"] == ar_tpp), key=lambda row: row["lr"])
        assert [r["lr"] for r in rows] == [0.00175, 0.0035, 0.007, 0.014]
        curve(name, style, [(i, r["mean_bpb"]) for i, r in enumerate(rows)])

    for family in ("ar", "mdlm"):
        table = tables[f"tables/{family}-grid.tex"]
        body = table.split(r"\midrule", 1)[1].split(r"\bottomrule", 1)[0].strip()
        rows = [line.removesuffix(r"\\").strip().split(" & ") for line in body.splitlines()]
        assert len(rows) == 12 and all(len(row) == 5 for row in rows)
        scores = [float(score) for row in rows for score in row[2:]]
        lo, hi = min(scores), max(scores)
        commands = []
        for group, budget in enumerate((20, 40, 80, 160)):
            group_rows = sorted((r for r in rows if int(r[0]) == budget), key=lambda r: float(r[1]))
            assert len(group_rows) == 3
            commands.append(rf"\budgettitle{{{group}}}{{{budget}}}")
            for col, (_, lr, *values) in enumerate(group_rows):
                x = group * 3.24 + col
                commands.append(rf"\ratelabel{{{x:.2f}}}{{{1000 * float(lr):.3g}}}")
                for row, value in enumerate(values):
                    shade = round(8 + 80 * (hi - float(value)) / (hi - lo))
                    commands.append(rf"\scorecell{{{x:.2f}}}{{{-row}}}{{{value}}}{{{shade}}}")
        marks.append("\\def\\" + family + "grid{%\n" + "\n".join(commands) + "\n}")
    return "\n".join(marks)


def render(block, replication, scaling, development, tables):
    outputs = {
        "figures/hp-grid-marks.tex": hp_grid_marks(development, tables),
        "figures/transfer-marks.tex": transfer_marks(scaling, block),
        "figures/evaluation-marks.tex": evaluation_marks(replication),
        "tables/block-rate-rows.tex": block_rate_rows(block),
        "tables/model-size-rows.tex": model_size_rows(scaling),
        "tables/decoding-control-rows.tex": decoding_control_rows(block),
        "tables/component-budget-rows.tex": component_rows(replication),
        "tables/final-model-rows.tex": final_model_rows(block),
    }
    return {path: HEADER + value + "\n" for path, value in outputs.items()}
