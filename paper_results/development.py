"""Best-fit four-layer development and hyperparameter screens."""

from functools import partial

from .formatting import bpb, bpb_delta, num
from .tables import add_table


def development_figure(points: list[dict]) -> str:
    labels = [
        r"Native\\AdamW",
        r"Role-specific\\AdamW",
        r"Muon\\scratch",
        r"Muon\\scratch",
        r"AR10 +\\MDLM30",
        r"Alternative\\backbone (37M)",
    ]
    lines = [
        r"% Generated by d4_development.py from the development endpoints.",
        r"\begin{tikzpicture}[x=2.26cm,y=10cm,font=\small]",
        r"\fill[blue!4] (-0.45,0) rectangle (2.5,0.40);",
        r"\fill[teal!5] (2.5,0) rectangle (5.48,0.40);",
        r"\node at (1,0.375) {20 tokens per counted parameter};",
        r"\node at (4,0.375) {40 tokens per counted parameter};",
        r"\node[rotate=90] at (-0.86,0.16) {NELBO (bits per byte)};",
    ]
    for tick in (1.35, 1.40, 1.45, 1.50, 1.55, 1.60):
        y = tick - 1.3
        lines.extend(
            [rf"\draw[black!12] (-0.45,{y:.2f}) -- (5.48,{y:.2f});", rf"\node[left] at (-0.45,{y:.2f}) {{{tick:.2f}}};"]
        )
    coords = [(i, row["bpb"] - 1.3) for i, row in enumerate(points)]
    plain_path = [
        f"({i},{y:.8f})" for (i, y), row in zip(coords, points, strict=True) if row["stage"] != "Backbone bundle"
    ]
    lines.append(r"\draw[black!50,thick] " + " -- ".join(plain_path) + ";")
    for (i, y), row, label in zip(coords, points, labels, strict=True):
        marker = r"\draw[black!70,thick,fill=white]" if row["stage"] == "Backbone bundle" else r"\fill[teal!75!black]"
        lines.extend(
            [
                rf"{marker} ({i},{y:.8f}) circle[radius=2pt];",
                rf"\node[above] at ({i},{y:.8f}) {{{bpb(row['bpb'])}}};",
                rf"\node[below,align=center,font=\footnotesize] at ({i},0) {{{label}}};",
            ]
        )
    return "\n".join([*lines, r"\end{tikzpicture}", ""])


def render(d):
    outputs = {}
    table = partial(add_table, outputs, "development")
    labels = [
        "Native AdamW, scratch",
        "Role-specific AdamW, scratch",
        "Muon, scratch",
        "Muon, scratch",
        r"Muon, AR10$\rightarrow$MDLM30",
        r"Nanochat-derived, AR10$\rightarrow$MDLM30",
    ]
    rows = [
        [label, num(r["physical_parameters"] / 1e6, 3), str(r["total_tpp"]), f"{r['lr']:g}", bpb(r["bpb"])]
        for label, r in zip(labels, d["development_path"], strict=True)
    ]
    table(
        "d4-development",
        "Development of the 20M baseline and 37M variant.",
        ["Model / training recipe", "Params (M)", "Total TPP", "Matrix LR", "NELBO BPB"],
        rows,
        "Training seed 47, best-fit document-isolated packing, context 1024, DB16, accumulation 4 and EB65,536. "
        "Each score averages four shared FP32 corruption plans on 1,680 document starts. The parameter column gives model totals; "
        "the TPP ledgers are 11,534,336 (plain) and 11,534,384 (nanochat-derived), excluding input/value embeddings. "
        "AR stages use matrix LR0.014. Rows compare whole tested recipes and are not additive effects or an isocompute path.",
        "lrrrr",
    )

    paired = d["paired_development"]
    rows = [
        [
            r["comparison"],
            str(r["seed"]),
            bpb(r["control_bpb"]),
            bpb(r["candidate_bpb"]),
            bpb_delta(r["candidate_bpb"] - r["control_bpb"]),
        ]
        for r in paired
    ]
    table(
        "d4-development-seeds",
        "Paired evidence for selected development steps.",
        ["Comparison", "Seed", "Control BPB", "Candidate BPB", r"$\Delta$ BPB"],
        rows,
        "Each checkpoint is scored on the same 1,680 document starts. Negative differences favor the candidate. "
        "Optimizer comparisons use TPP20 and separately selected rates, including auxiliary-group changes in the native/role-specific contrast. "
        "Allocation and backbone comparisons include parent cost at total TPP40; the backbone comparison changes both stages and the total parameter count. "
        "Fresh seeds 48/49 confirm allocation, whereas the backbone comparison uses 47/48. Reused controls are not new independent runs; two seeds are not a precise variance estimate.",
        "lrrrr",
    )

    allocation = {(r["ar_tpp"], 0.007): r["bpb"] for r in d["allocation_grid"]}
    for r in d["conversion_lr"]:
        key = (r["ar_tpp"], r["lr"])
        if key in allocation:
            assert allocation[key] == r["mean_bpb"]
        allocation[key] = r["mean_bpb"]
    rates = [0.00175, 0.0035, 0.007, 0.014]
    rows = [[str(ar), str(40 - ar), *[bpb(allocation.get((ar, lr))) for lr in rates]] for ar in [0, 5, 10, 20, 30, 35]]
    table(
        "d4-hp-allocation",
        "20M token-budget allocation and continuation learning rates.",
        ["AR TPP", "MDLM TPP", *[f"LR{lr:g}" for lr in rates]],
        rows,
        "Seed 47, plain backbone, total TPP40, EB64K and WSD. Entries are document-start NELBO BPB. "
        "The LR0.007 column is the full allocation screen; only 10/30 and 20/20 received the additional continuation-LR bracket. "
        "The 0/40 row is independently scheduled scratch training, not a parent continuation. AR stages use LR0.014. "
        "At conversion, weights transfer but optimizer, loader, RNG and counters reset; stages can revisit source data. "
        "A dash is untested. These are matched search slices, not independently optimized allocations.",
        "rrrrrr",
    )

    rates = [0.0035, 0.007, 0.014, 0.028]
    schedule = {(r["horizon"], r["shape"], r["lr"]): r["mean_bpb"] for r in d["schedule_lr"]}
    rows = [
        [str(tpp), shape_label, *[bpb(schedule.get((tpp, shape, lr))) for lr in rates]]
        for tpp in (20, 160)
        for shape, shape_label in [("wsd", "WSD"), ("linear", "Full-linear")]
    ]
    table(
        "d4-hp-schedule",
        "20M scratch-MDLM schedule and learning-rate screen.",
        ["TPP", "Schedule", *[f"LR{lr:g}" for lr in rates]],
        rows,
        "Seed 47, plain Muon, best-fit packing, context 1024 and EB64K. Entries are document-start NELBO BPB. "
        "Both schedules have 5\\% warmup and zero terminal LR. WSD holds the peak before a 30\\% linear cooldown; full-linear decays over the remaining 95\\%. "
        "Every horizon is separately scheduled. The new TPP20 linear LR0.028 endpoint worsens on 0.014 by 0.057 BPB. "
        "At TPP160, both best tested rates remain at the lower boundary. Dashes are untested, not interpolated.",
        "rlrrrr",
    )

    batches = {}
    for r in d["batch_horizon"] + d["short_batch_lr"] + d["long_budget"]:
        key = (r["horizon"], r["seed"], r["lr"], r["eb"])
        if key in batches:
            assert batches[key] == r["mean_bpb"]
        batches[key] = r["mean_bpb"]
    ebs = [32768, 65536, 131072, 262144, 524288]
    rows = [
        [str(tpp), str(seed), f"{lr:g}", *[bpb(batches.get((tpp, seed, lr, eb))) for eb in ebs]]
        for tpp, seed, lr in [(20, 47, 0.0035), (20, 47, 0.007), (160, 47, 0.007), (160, 48, 0.007), (160, 49, 0.007)]
    ]
    table(
        "d4-hp-batch",
        "20M scratch-MDLM batch size across training horizons.",
        ["TPP", "Seed", "Matrix LR", *[f"EB{eb // 1024}K" for eb in ebs]],
        rows,
        "WSD, plain Muon, best-fit packing, context 1024; raw document-start NELBO BPB. "
        "K=1,024 global source tokens/update. Seed 47 provides the screen; seeds 48/49 provide fresh TPP160 confirmation and the 512K extension. "
        "At TPP20, EB32K is worse than its same-LR EB64K control by 0.011 (LR0.0035) and 0.019 (LR0.007). "
        "Matched batch effects subtract the 64K entry within a row; equal zeros across rows would not imply equal absolute performance. "
        "At fixed tokens, EB changes update count as well as gradient averaging. Dashes are untested; the table is not a complete joint LR/batch search.",
        "rrrrrrrr",
    )

    outputs["figures/d4-development.tex"] = development_figure(d["development_path"])
    return outputs
